#!/usr/bin/env bash
# One-command deploy of Hermes Agent to a VPS.
#
#   ./deploy.sh                # first run: asks a few questions, generates a password, deploys
#                              # later runs: re-deploys / upgrades with the saved settings
#   ./deploy.sh --tags hermes  # extra args go to ansible-playbook (here: only the Hermes stack)
#
# Settings (incl. secrets) are saved to ansible/inventory/hosts.yml and the login to
# credentials.txt next to this script. Both are gitignored and chmod 600.
# To change the password: edit hermes_dashboard_password in hosts.yml and re-run.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
ANSIBLE_DIR="$ROOT/ansible"
INVENTORY="$ANSIBLE_DIR/inventory/hosts.yml"
CREDENTIALS="$ROOT/credentials.txt"

bold() { printf '\033[1m%s\033[0m\n' "$*"; }
die() { printf 'Error: %s\n' "$*" >&2; exit 1; }

ask() { # ask VAR "Question" [default]
  local __var="$1" __q="$2" __def="${3:-}" __ans
  if [ -n "$__def" ]; then read -r -p "$__q [$__def]: " __ans; else read -r -p "$__q: " __ans; fi
  __ans="${__ans:-$__def}"
  [ -n "$__ans" ] || die "$__q is required"
  printf -v "$__var" '%s' "$__ans"
}

yaml_quote() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/''/g")"; } # YAML single-quoted scalar

random_password() { openssl rand -base64 48 | LC_ALL=C tr -dc 'A-Za-z0-9' | cut -c1-24; }

# Read a top-level host var back from hosts.yml (simple "  key: 'value'" lines we wrote ourselves).
inv_get() { sed -n "s/^      $1: '\(.*\)'\$/\1/p" "$INVENTORY" | head -1 | sed "s/''/'/g"; }

for cmd in ansible-playbook ansible-galaxy openssl ssh; do
  command -v "$cmd" >/dev/null || die "'$cmd' not found (macOS: brew install ansible)"
done

# ---------------------------------------------------------------- settings
if [ ! -f "$INVENTORY" ]; then
  bold "First run: a few questions (saved to ansible/inventory/hosts.yml)"
  echo "(Ansible logs in as root with your SSH key: it must already be authorized for root.)"
  ask VPS_IP "VPS address (IP, or a Host alias from ~/.ssh/config)"
  ask DOMAIN "Domain for Hermes (DNS A record must point to the VPS)"
  ask ACME_EMAIL "Email for Let's Encrypt expiry notices"
  ask DASH_USER "Hermes admin username" "admin"
  ask STAGING "Use Let's Encrypt staging certs (for testing, browser will warn)? y/N" "n"
  case "$STAGING" in [yY]*) STAGING=true ;; *) STAGING=false ;; esac

  NEW_PASS="$(random_password)"
  NEW_SECRET="$(openssl rand -hex 32)"
  [ ${#NEW_PASS} -eq 24 ] || die "password generation failed"

  umask 077
  cat >"$INVENTORY" <<EOF
# Generated by deploy.sh on $(date +%F). Contains secrets: gitignored, keep private.
all:
  hosts:
    hermes:
      ansible_host: $(yaml_quote "$VPS_IP")
      ansible_user: 'root'
      hermes_domain: $(yaml_quote "$DOMAIN")
      acme_email: $(yaml_quote "$ACME_EMAIL")
      acme_staging: $STAGING
      hermes_dashboard_username: $(yaml_quote "$DASH_USER")
      hermes_dashboard_password: '$NEW_PASS'
      hermes_dashboard_session_secret: '$NEW_SECRET'
EOF
  chmod 600 "$INVENTORY"
  bold "Saved settings and a generated password to ansible/inventory/hosts.yml"
else
  bold "Using saved settings from ansible/inventory/hosts.yml"
fi

VPS_IP="$(inv_get ansible_host)"
DOMAIN="$(inv_get hermes_domain)"
DASH_USER="$(inv_get hermes_dashboard_username)"
DASH_PASS="$(inv_get hermes_dashboard_password)"
[ -n "$VPS_IP" ] && [ -n "$DOMAIN" ] && [ -n "$DASH_PASS" ] || die "hosts.yml is missing settings; delete it and re-run"

cd "$ANSIBLE_DIR"

# ---------------------------------------------------------------- dependencies
bold "Installing Ansible collections"
ansible-galaxy collection install -r requirements.yml -p collections >/dev/null

# ---------------------------------------------------------------- SSH check
ssh -o BatchMode=yes -o ConnectTimeout=8 -o StrictHostKeyChecking=accept-new "root@$VPS_IP" true \
  || die "can't SSH to root@$VPS_IP with a key. Authorize your SSH key for root first."

# ---------------------------------------------------------------- deploy
bold "Configuring the server and deploying Hermes"
ansible-playbook site.yml "$@"

# ---------------------------------------------------------------- credentials
umask 077
cat >"$CREDENTIALS" <<EOF
Hermes Agent: $(date '+%F %T')

Dashboard:  https://$DOMAIN
Username:   $DASH_USER
Password:   $DASH_PASS

Hermes Desktop: Settings > Gateways > Remote gateway > https://$DOMAIN, then Sign in.
Server SSH: ssh root@$VPS_IP    (stack lives in /opt/hermes)
EOF
chmod 600 "$CREDENTIALS"

echo
bold "Done. Hermes is deployed."
cat "$CREDENTIALS"
echo
echo "(Saved to $CREDENTIALS)"
